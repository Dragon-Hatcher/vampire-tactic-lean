#!/usr/bin/env python3
"""Regenerates replay/VampireReplay/InferenceRule.lean from vampire's Inference.hpp.

  ./scripts/gen-inference-rules.py [vampire checkout]

The checkout defaults to the one `lake build` builds against, chosen the way
lakefile.lean chooses it: `$VAMPIRE_DIR` if set, then a sibling `vampire-fork/`
if there is one, and otherwise the pinned revision Lake fetched into
`.lake/build/vampire`.

The enum's body runs to the first line starting with `};`, and a rule is a
line holding an upper-case name followed by a comma, so the closing
`GENERIC_THEORY_AXIOM_LAST` marker is not one. The name a TPTP proof writes
each rule by is read from `Kernel::ruleName` in Kernel/Inference.cpp.
"""
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / "replay" / "VampireReplay" / "InferenceRule.lean"

LEAN_KEYWORDS = {
    "axiom", "def", "theorem", "instance", "end", "exists", "forall", "fun",
    "have", "let", "match", "with", "do", "if", "then", "else", "from",
    "structure", "class", "where", "deriving", "open", "section", "namespace",
    "variable", "universe", "set_option", "example", "mutual", "partial",
    "unsafe", "private", "protected", "true", "false", "and", "or", "not",
    "in", "at", "by", "calc", "show", "this", "sorry", "rec", "type",
}


def camel(name: str) -> str:
    head, *rest = name.lower().split("_")
    ident = head + "".join(word.capitalize() for word in rest)
    return f"«{ident}»" if ident in LEAN_KEYWORDS else ident


def main() -> int:
    if len(sys.argv) > 1:
        root = sys.argv[1]
    elif os.environ.get("VAMPIRE_DIR"):
        root = os.environ["VAMPIRE_DIR"]
        if not (Path(root) / "CMakeLists.txt").exists():
            print(f"VAMPIRE_DIR is set to {root}, which holds no CMakeLists.txt",
                  file=sys.stderr)
            return 1
    elif (HERE.parent / "vampire-fork" / "CMakeLists.txt").exists():
        root = str(HERE.parent / "vampire-fork")
    else:
        root = str(HERE / ".lake" / "build" / "vampire")
    header = f"{root}/Kernel/Inference.hpp"
    body = re.search(
        r"enum class InferenceRule : unsigned char \{(.*?)\n\};",
        open(header).read(),
        re.S,
    )
    if body is None:
        print(f"could not find InferenceRule in {header}", file=sys.stderr)
        return 1
    if re.search(r"^[ \t]*([A-Z][A-Z_0-9]*)[ \t]*=", body.group(1), re.M):
        print("InferenceRule now assigns explicit values", file=sys.stderr)
        return 1
    names = re.findall(r"^[ \t]*([A-Z][A-Z_0-9]*)[ \t]*,", body.group(1), re.M)
    if len(names) != len(set(names)):
        print("InferenceRule has duplicate names", file=sys.stderr)
        return 1
    # The name each rule is written by in a TPTP proof: vampire's name for it
    # (`Kernel::ruleName`), with `_` for its spaces. The markers that bound
    # the enum's ranges share one, and no proof names them; any other rule
    # has to have a name of its own, or a proof could not say which it is.
    source = open(f"{root}/Kernel/Inference.cpp").read().splitlines()
    try:
        start = next(i for i, l in enumerate(source)
                     if l.startswith("std::string Kernel::ruleName(InferenceRule rule)"))
    except StopIteration:
        print(f"could not find ruleName in {root}/Kernel/Inference.cpp", file=sys.stderr)
        return 1
    end = next(i for i in range(start + 1, len(source)) if source[i].startswith("}"))
    display, pending = {}, []
    for line in source[start:end]:
        pending += re.findall(r"case InferenceRule::(\w+):", line)
        returned = re.search(r'return "([^"]*)"', line)
        if returned:
            for rule in pending:
                display[rule] = returned.group(1).replace(" ", "_")
            pending = []
    missing = [n for n in names if n not in display]
    if missing:
        print(f"ruleName gives no name to {missing}", file=sys.stderr)
        return 1
    sharing = {}
    for n in names:
        sharing.setdefault(display[n], []).append(n)
    marker = lambda n: n.startswith("GENERIC_")
    tptp = {}
    for shown, rules in sharing.items():
        if len(rules) == 1:
            tptp[rules[0]] = shown
        elif not all(marker(r) for r in rules):
            print(f"ruleName gives {rules} the one name {shown!r}", file=sys.stderr)
            return 1
    commit = subprocess.run(
        ["git", "-C", root, "rev-parse", "--short", "HEAD"],
        capture_output=True, text=True,
    ).stdout.strip()

    out = [
        "-- Generated by scripts/gen-inference-rules.py from vampire's",
        f"-- Kernel/Inference.hpp at {commit}. Do not edit.",
        "",
        "namespace Vampire",
        "",
        "/-- Vampire's `Kernel::InferenceRule`, in declaration order. -/",
        "inductive InferenceRule where",
    ]
    out += [f"  | {camel(n)}" for n in names]
    out += [
        "deriving Inhabited, Repr, BEq, DecidableEq",
        "",
        "namespace InferenceRule",
        "",
        "/-- Vampire's own name for a rule. -/",
        "def name : InferenceRule → String",
    ]
    out += [f"  | .{camel(n)} => \"{n.lower()}\"" for n in names]
    out += [
        "",
        "/-- The rule a TPTP proof names. -/",
        "def ofTptpName? : String → Option InferenceRule",
    ]
    out += [f"  | \"{tptp[n]}\" => some .{camel(n)}" for n in names if n in tptp]
    out += [
        "  | _ => none",
        "",
        "instance : ToString InferenceRule := ⟨name⟩",
        "",
        "end InferenceRule",
        "",
        "end Vampire",
        "",
    ]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(HERE)} with {len(names)} rules")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
